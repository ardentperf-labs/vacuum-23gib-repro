#!/usr/bin/env python3
"""Publish standalone per-run reports with embedded, evidence-linked timelines.

Default mode is a read-only dry run. ``--write`` updates only each run's
results/REPORT.md, replacing the two generated blocks while preserving any
content outside them. This does not touch the aggregate repository REPORT.md.
"""
